def all_equipment_codes() -> list[str]:
    """Return the distinct HS6 codes used by all equipment series."""
    return sorted(
        set().union(*(definition["codes"] for definition in SERIES.values()))
    )


def series_for_code(cmd_code: str, *_unused) -> set[str]:
    """Return the equipment series to which an exact HS6 code belongs."""
    code = str(cmd_code).strip().zfill(6)
    return {
        key
        for key, definition in SERIES.items()
        if code in definition["codes"]
    }
